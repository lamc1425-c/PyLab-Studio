export function normalizeLanguage(language) {
  const value = String(language ?? "").toLowerCase().split("-")[0];
  return SUPPORTED_LANGUAGES.includes(value) ? value : "en";
}

export function detectLanguage(languages = globalThis.navigator?.languages ?? [globalThis.navigator?.language]) {
  for (const language of languages ?? []) {
    const normalized = normalizeLanguage(language);
    if (SUPPORTED_LANGUAGES.includes(normalized) && String(language ?? "").toLowerCase().startsWith(normalized)) {
      return normalized;
    }
  }
  return "en";
}

export function languageOption(language) {
  const normalized = normalizeLanguage(language);
  return LANGUAGE_OPTIONS.find((option) => option.id === normalized) ?? LANGUAGE_OPTIONS[0];
}

export function translate(language, key, variables = {}) {
  const normalized = normalizeLanguage(language);
  const template = MESSAGES[normalized]?.[key] ?? MESSAGES.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}
